ON public.attendance_logs
FOR SELECT TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.bookings b
        JOIN public.events e
          ON e.event_id = b.event_id
        WHERE b.booking_id = attendance_logs.booking_id
          AND e.coordinator_id = auth.uid()
    )
);


