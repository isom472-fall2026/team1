-- ============================================================
-- BOOKING CAPACITY / WAITLIST
-- ============================================================

CREATE OR REPLACE FUNCTION public.set_booking_status()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SET search_path = ''
AS $$
DECLARE
    event_capacity INTEGER;
    confirmed_count INTEGER;
BEGIN

    -- Lock bookings for this event so simultaneous reservations
    -- cannot exceed capacity.
    PERFORM pg_advisory_xact_lock(NEW.event_id);

    SELECT capacity
    INTO event_capacity
    FROM public.events
    WHERE event_id = NEW.event_id;

    IF event_capacity IS NULL THEN
        RAISE EXCEPTION 'Event does not exist.';
    END IF;

    SELECT COUNT(*)
    INTO confirmed_count
    FROM public.bookings
    WHERE event_id = NEW.event_id
      AND status = 'Confirmed';

    IF confirmed_count >= event_capacity THEN
        NEW.status := 'Waitlisted';
    ELSE
        NEW.status := 'Confirmed';
    END IF;

    RETURN NEW;
END;
$$;


CREATE TRIGGER automatic_booking_status_trigger
BEFORE INSERT ON public.bookings
FOR EACH ROW
EXECUTE FUNCTION public.set_booking_status();


