CREATE TABLE public.users (
    user_id UUID PRIMARY KEY
        REFERENCES auth.users(id) ON DELETE CASCADE,
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(30),
    university_id VARCHAR(50) UNIQUE
);


CREATE TABLE public.attendee (
    user_id UUID PRIMARY KEY
        REFERENCES public.users(user_id) ON DELETE CASCADE,
    attendee_type VARCHAR(20) NOT NULL,

    CONSTRAINT attendee_type_check
        CHECK (attendee_type IN ('Student', 'StaffFaculty', 'Guest'))
);


CREATE TABLE public.coordinator (
    user_id UUID PRIMARY KEY
        REFERENCES public.users(user_id) ON DELETE CASCADE,
    office VARCHAR(100),
    department VARCHAR(100)
);


CREATE TABLE public.organizer (
    user_id UUID PRIMARY KEY
        REFERENCES public.users(user_id) ON DELETE CASCADE,
    department VARCHAR(100)
);


CREATE TABLE public.venues (
    venue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_name VARCHAR(150) NOT NULL,
    location VARCHAR(150) NOT NULL,
    room_capacity INTEGER NOT NULL,

    CONSTRAINT room_capacity_check
        CHECK (room_capacity > 0)
);


CREATE TABLE public.events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    event_type VARCHAR NOT NULL,
    event_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    capacity INTEGER NOT NULL,

    coordinator_id UUID NOT NULL
        REFERENCES public.coordinator(user_id) ON DELETE RESTRICT,

    venue_id BIGINT NOT NULL
        REFERENCES public.venues(venue_id) ON DELETE RESTRICT,

    CONSTRAINT event_capacity_check
        CHECK (capacity > 0),

    CONSTRAINT event_time_check
        CHECK (end_time > start_time),

    CONSTRAINT event_type_check
        CHECK (event_type IN ('Play', 'Workshop', 'Seminar'))
);


CREATE TABLE public.bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id UUID NOT NULL
        REFERENCES public.attendee(user_id) ON DELETE CASCADE,

    event_id BIGINT NOT NULL
        REFERENCES public.events(event_id) ON DELETE CASCADE,

    booking_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    status VARCHAR(20) NOT NULL DEFAULT 'Confirmed',

    CONSTRAINT booking_status_check
        CHECK (status IN ('Confirmed', 'Waitlisted', 'Cancelled')),

    CONSTRAINT unique_user_event
        UNIQUE (user_id, event_id)
);


CREATE TABLE public.organizer_assignments (
    event_id BIGINT NOT NULL
        REFERENCES public.events(event_id) ON DELETE CASCADE,

    organizer_id UUID NOT NULL
        REFERENCES public.organizer(user_id) ON DELETE CASCADE,

    PRIMARY KEY (event_id, organizer_id)
);


CREATE TABLE public.attendance_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_id BIGINT NOT NULL UNIQUE
        REFERENCES public.bookings(booking_id) ON DELETE CASCADE,

    organizer_id UUID NOT NULL
        REFERENCES public.organizer(user_id) ON DELETE RESTRICT,

    check_in_time TIMESTAMPTZ,
    check_out_time TIMESTAMPTZ,

    attendance_status VARCHAR(20) NOT NULL,

    CONSTRAINT attendance_status_check
        CHECK (attendance_status IN ('Present', 'Absent')),

    CONSTRAINT checkout_after_checkin
        CHECK (
            check_out_time IS NULL
            OR check_in_time IS NULL
            OR check_out_time >= check_in_time
        )
);


