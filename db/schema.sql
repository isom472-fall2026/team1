CREATE OR REPLACE FUNCTION public.validate_event_capacity()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SET search_path = ''
AS $$
DECLARE
    max_capacity INTEGER;
BEGIN

    SELECT room_capacity
    INTO max_capacity
    FROM public.venues
    WHERE venue_id = NEW.venue_id;

    IF max_capacity IS NULL THEN
        RAISE EXCEPTION 'Venue does not exist.';
    END IF;

    IF NEW.capacity > max_capacity THEN
        RAISE EXCEPTION
            'Event capacity cannot exceed venue room capacity.';
    END IF;

    RETURN NEW;
END;
$$;


CREATE TRIGGER validate_event_capacity_trigger
BEFORE INSERT OR UPDATE ON public.events
FOR EACH ROW
EXECUTE FUNCTION public.validate_event_capacity();


CREATE OR REPLACE FUNCTION public.prevent_event_overlap()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SET search_path = ''
AS $$
BEGIN

    IF EXISTS (
        SELECT 1
        FROM public.events e
        WHERE e.venue_id = NEW.venue_id
          AND e.event_date = NEW.event_date
          AND e.event_id <> COALESCE(NEW.event_id, 0)
          AND NEW.start_time < e.end_time
          AND NEW.end_time > e.start_time
    )
    THEN
        RAISE EXCEPTION
            'Another event is already scheduled in this venue during this time.';
    END IF;

    RETURN NEW;
END;
$$;


CREATE TRIGGER prevent_event_overlap_trigger
BEFORE INSERT OR UPDATE ON public.events
FOR EACH ROW
EXECUTE FUNCTION public.prevent_event_overlap();


-- ============================================================
-- ATTENDANCE VALIDATION
-- ============================================================

CREATE OR REPLACE FUNCTION public.validate_attendance()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SET search_path = ''
AS $$
DECLARE
    booking_event BIGINT;
    current_booking_status VARCHAR(20);
BEGIN

    SELECT event_id, status
    INTO booking_event, current_booking_status
    FROM public.bookings
    WHERE booking_id = NEW.booking_id;

    IF booking_event IS NULL THEN
        RAISE EXCEPTION 'Booking does not exist.';
    END IF;

    IF current_booking_status <> 'Confirmed' THEN
        RAISE EXCEPTION
            'Attendance can only be recorded for confirmed bookings.';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.organizer_assignments
        WHERE event_id = booking_event
          AND organizer_id = NEW.organizer_id
    )
    THEN
        RAISE EXCEPTION
            'Organizer is not assigned to this event.';
    END IF;

    RETURN NEW;
END;
$$;


CREATE TRIGGER validate_attendance_trigger
BEFORE INSERT OR UPDATE ON public.attendance_logs
FOR EACH ROW
EXECUTE FUNCTION public.validate_attendance();


